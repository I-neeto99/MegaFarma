-- ---------------------------------------------------------------------
-- DDD_CLIENTES
-- ---------------------------------------------------------------------
CREATE TABLE DDD_CLIENTES (
    CODIGO    NUMBER          GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME      VARCHAR2(100)   NOT NULL,
    CPF       VARCHAR2(11),
    CONSTRAINT DDD_CLIENTES_PK PRIMARY KEY (CODIGO)
);

-- ---------------------------------------------------------------------
-- DDD_REMEDIOS
-- ---------------------------------------------------------------------
CREATE TABLE DDD_REMEDIOS (
    CODIGO               NUMBER         GENERATED BY DEFAULT ON NULL AS IDENTITY,
    NOME                 VARCHAR2(100)  NOT NULL,
    PRECO                NUMBER(6,2),
    DATA_DE_FABRICACAO   DATE,
    DATA_DE_VALIDADE     DATE,
    CONSTRAINT DDD_REMEDIOS_PK PRIMARY KEY (CODIGO)
);

-- ---------------------------------------------------------------------
-- DDD_VENDAS
-- ---------------------------------------------------------------------
CREATE TABLE DDD_VENDAS (
    CODIGO          NUMBER   GENERATED BY DEFAULT ON NULL AS IDENTITY,
    DATA_DA_VENDA   DATE     DEFAULT SYSDATE,
    CODCLIENTE      NUMBER,
    CONSTRAINT DDD_VENDAS_PK PRIMARY KEY (CODIGO),
    CONSTRAINT DDD_VENDAS_CLIENTE_FK FOREIGN KEY (CODCLIENTE)
        REFERENCES DDD_CLIENTES (CODIGO)
);

-- ---------------------------------------------------------------------
-- DDD_ITENSVENDIDOS (tabela associativa: chave primaria composta)
-- ---------------------------------------------------------------------
CREATE TABLE DDD_ITENSVENDIDOS (
    CODVENDA     NUMBER   NOT NULL,
    CODREMEDIO   NUMBER   NOT NULL,
    QUANTIDADE   NUMBER   DEFAULT 1 NOT NULL,
    CONSTRAINT DDD_ITENSVENDIDOS_PK PRIMARY KEY (CODVENDA, CODREMEDIO),
    CONSTRAINT DDD_ITENS_VENDA_FK FOREIGN KEY (CODVENDA)
        REFERENCES DDD_VENDAS (CODIGO),
    CONSTRAINT DDD_ITENS_REMEDIO_FK FOREIGN KEY (CODREMEDIO)
        REFERENCES DDD_REMEDIOS (CODIGO),
    CONSTRAINT DDD_ITENS_QTD_CK CHECK (QUANTIDADE > 0)
);
